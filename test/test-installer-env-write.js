test('encodeEnvValue lässt einfache Werte unverändert (bare)', () => {
  for (const v of ['abc123', 'Europe/Berlin', 'https://dav.example.test', '/yuvomi/documents', 'true', '587']) {
    assert.equal(encodeEnvValue(v), v, `"${v}" sollte unquoted bleiben`);
  }
});

test('encodeEnvValue quotet Werte mit Whitespace/# und escaped Quotes/Backslash', () => {
  assert.equal(encodeEnvValue('pass word'), '"pass word"');
  assert.equal(encodeEnvValue(' leading'), '" leading"');
  assert.equal(encodeEnvValue('a # b'), '"a # b"');
  assert.equal(encodeEnvValue('say "hi"'), '"say \\"hi\\""');
  assert.equal(encodeEnvValue('back\\slash'), '"back\\\\slash"');
});

test('encodeEnvValue verdoppelt $ zum Compose-Literal ($ -> $$)', () => {
  // Ohne Quoting-Bedarf: nur $ verdoppelt.
  assert.equal(encodeEnvValue('p$w0rd'), 'p$$w0rd');
  // Mit Quoting-Bedarf (Space): gequotet UND $ verdoppelt.
  assert.equal(encodeEnvValue('p$ w'), '"p$$ w"');
});

test('renderEnvFile schützt ein Passwort mit Sonderzeichen vor Compose-Fehlinterpretation', () => {
  const out = renderEnvFile({ EMAIL_SMTP_PASS: 'S3cr#t $val ue' });
  assert.match(out, /^EMAIL_SMTP_PASS="S3cr#t \$\$val ue"$/m);
});

test('backupEnvFile sichert bestehende .env und gibt null ohne .env', () => {
  const dir = mkdtempSync(join(tmpdir(), 'oikos-env-'));
  try {
    const envPath = join(dir, '.env');
    assert.equal(backupEnvFile(envPath), null);
    writeFileSync(envPath, 'OLD=1\n');
    const backup = backupEnvFile(envPath);
    assert.ok(backup && existsSync(backup), 'Backup-Datei wurde nicht angelegt');
    assert.match(backup, /\.env\.bak-/);
    assert.equal(readFileSync(backup, 'utf8'), 'OLD=1\n');
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});

// ── HTTP routes ──────────────────────────────────────────────────────────────

async function withServer(root, fn) {
  const prev = process.env.OIKOS_INSTALLER_ROOT;
  process.env.OIKOS_INSTALLER_ROOT = root;
  const server = createInstallerServer();
  await new Promise(r => server.listen(0, '127.0.0.1', r));
  const { port } = server.address();
  try {
    await fn(`http://127.0.0.1:${port}`);
  } finally {
    await new Promise(r => server.close(r));
    if (prev === undefined) delete process.env.OIKOS_INSTALLER_ROOT;
    else process.env.OIKOS_INSTALLER_ROOT = prev;
  }
}

