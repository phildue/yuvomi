// ── Bewahrte Schlüssel über einen Installer-Rerun ────────────────────────────
//
// Ein neu erzeugter DB_ENCRYPTION_KEY macht die verschlüsselte Datenbank
// unlesbar; der Start bricht dann mit „Wrong encryption key" ab. Ein Rerun
// (Update, Portwechsel, nachgetragenes SMTP) darf eine laufende Installation
// nicht so zerlegen — deshalb überleben diese Schlüssel jeden Durchlauf.

test('decodeEnvValue dreht encodeEnvValue zurück (Roundtrip)', () => {
  for (const raw of ['plain', 'a b c', 'pa$$w0rd', 'has "quotes"', 'back\\slash', '#hash', 'mixed $x "y" \\z']) {
    assert.equal(decodeEnvValue(encodeEnvValue(raw)), raw, `Roundtrip fehlgeschlagen für: ${raw}`);
  }
});

test('readEnvFile liest Werte, überspringt Kommentare und fehlende Dateien', () => {
  const dir = mkdtempSync(join(tmpdir(), 'oikos-env-'));
  try {
    assert.deepEqual(readEnvFile(join(dir, '.env')), {}, 'fehlende Datei muss {} liefern');
    writeFileSync(join(dir, '.env'), [
      '# Generated by Yuvomi Installer',
      'SESSION_SECRET=abc123',
      `DB_ENCRYPTION_KEY=${encodeEnvValue('pa$$ w0rd')}`,
      '',
      'WEATHER_CITY=Berlin',
    ].join('\n'));
    const env = readEnvFile(join(dir, '.env'));
    assert.equal(env.SESSION_SECRET, 'abc123');
    assert.equal(env.DB_ENCRYPTION_KEY, 'pa$$ w0rd', 'compose-kodierter Wert muss dekodiert ankommen');
    assert.equal(env.WEATHER_CITY, 'Berlin');
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});

