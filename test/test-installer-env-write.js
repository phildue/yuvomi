test('install.sh übernimmt einen bestehenden Schlüssel aus der .env', () => {
  // Die Helper-Funktion isoliert ausführen: install.sh selbst startet am Ende
  // den interaktiven Wizard, lässt sich also nicht einfach sourcen.
  const src = readFileSync(new URL('../install.sh', import.meta.url), 'utf8');
  const start = src.indexOf('read_existing_env_value() {');
  const end = src.indexOf('on_interrupt()');
  assert.ok(start !== -1 && end > start, 'read_existing_env_value nicht in install.sh gefunden');
  const fn = src.slice(start, end);

  const dir = mkdtempSync(join(tmpdir(), 'oikos-env-'));
  try {
    const run = key => execFileSync('bash', ['-c', `${fn}\nread_existing_env_value ${key} || printf '<none>'`],
      { cwd: dir, encoding: 'utf8' });

    assert.equal(run('DB_ENCRYPTION_KEY'), '<none>', 'ohne .env darf nichts gefunden werden');

    // Genau so schreibt der Web-Installer: compose-sicher kodiert.
    writeFileSync(join(dir, '.env'), [
      '# Generated by Yuvomi Installer',
      'SESSION_SECRET=schlicht',
      `DB_ENCRYPTION_KEY=${encodeEnvValue('pa$$ w0rd')}`,
    ].join('\n') + '\n');

    assert.equal(run('SESSION_SECRET'), 'schlicht');
    assert.equal(run('DB_ENCRYPTION_KEY'), 'pa$$ w0rd',
      'ein CLI-Rerun nach einer Web-Installation muss denselben Schlüssel lesen');
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});

